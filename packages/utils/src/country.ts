/** A missing or non-CN country means free-text plate entry (the default). */
export function isMainlandChina(country: string | null | undefined): boolean {
  return country?.trim().toUpperCase() === MAINLAND_CHINA
}

/**
 * The country's name in the UI language, e.g. ('DE', 'en') → 'Germany',
 * ('DE', 'zh-CN') → '德国'. Falls back to the code where the runtime has no
 * `Intl.DisplayNames` (old WebViews) or does not know it. Callers that need
 * "mainland China" rather than the runtime's "China" label CN themselves.
 */
export function countryName(code: string, locale: string): string {
  try {
    return new Intl.DisplayNames([locale], { type: 'region' }).of(code) ?? code
  } catch {
    return code
  }
}
